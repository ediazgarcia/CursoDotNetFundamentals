
// La sentencia switch se utiliza para ejecutar diferentes bloques de código según el valor de una expresión. La sintaxis básica es la siguiente:


int opcion = 0;

switch (opcion)
{
    case 1:
        Console.WriteLine("Opción 1 seleccionada");
        break;
    case 2:
        Console.WriteLine("Opción 2 seleccionada");
        break;
    case 3:
        Console.WriteLine("Opción 3 seleccionada");
        break;
    default:
        Console.WriteLine("Opción no válida");
        break;
}